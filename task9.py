print("=== Програма привітання ===")

while True:
    name = input("\nВведіть ваше ім'я (або 'exit' для виходу): ").strip()

    # Перевірка на вихід з програми
    if name.lower() == 'exit':
        print("Завершення роботи програми. До побачення!")
        break

    # Перевірка на порожнє введення
    if name:
        print(f"Привіт, {name}!")
    else:
        print("Ви не ввели ім'я! Спробуйте ще раз.")