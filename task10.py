print("=== Програма конвертації віку з років у дні ===")

try:
    years = int(input("Введіть ваш вік у роках (наприклад, 18): "))

    if years < 0 or years > 120:
        print("\nПомилка: Введіть реальний вік у діапазоні від 0 до 120 років!")
    else:
        days = years * 365
        print(f"\nВаш вік: {years} років (це приблизно {days} днів).")

except ValueError:
    print("\nПомилка: Введіть вік цілим числом, а не текстом чи дробом!")